const assert = require('node:assert/strict');

module.exports = async function batchExportUi(window, { search, scrollToEnd, waitForRenderer, pause }) {
  const ui = expression => window.webContents.executeJavaScript(expression);
  const click = text => ui(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes(${JSON.stringify(text)})).click()`);
  const wait = (expression, label) => waitForRenderer(window, expression, label);
  await search();
  assert.equal(await ui("[...document.querySelectorAll('[aria-label=\"Application actions\"] button')].filter(b=>b.textContent.includes('Export')).length"), 1);
  await ui("window.singleExports=[]; window.cifApi.exportCif=async id=>{window.singleExports.push(id);return {exported:true,fileName:'NaCl_1.cif'};}; undefined");
  await click('Export\u2026');
  await wait("document.querySelector('dialog button:last-child')?.textContent.includes('Save CIF')", 'highlighted export default');
  assert.equal(await ui("document.querySelectorAll('input[name=batch-scope]')[1].disabled"), false);
  await click('Save CIF');
  await wait("document.querySelector('dialog')?.textContent.includes('Exported NaCl_1.cif')", 'single export success');
  assert.equal(await ui('window.singleExports[0]'), 1);
  await ui("window.cifApi.exportCif=async()=>({exported:false}); undefined");
  await click('Save CIF');
  await wait("document.querySelector('dialog')?.textContent.includes('Export cancelled.')", 'single picker cancellation');
  // A string retains its diagnostic across executeJavaScript worlds.
  await ui("window.cifApi.exportCif=async()=>{throw 'Export failed test'}; undefined");
  await click('Save CIF');
  await wait("document.querySelector('dialog [role=alert]')?.textContent.includes('Export failed test')", 'single export error');
  await click('Close');
  assert.equal(await ui("document.querySelectorAll('[data-testid=data-grid-scroll] input[type=checkbox]').length"), 0);
  assert.equal(await ui("[...document.querySelectorAll('button')].some(b=>b.textContent==='Clear selection')"), false);
  const rowClick = (id, modifiers = {}) => ui(`document.querySelector('tr[data-entry-id="${id}"]').dispatchEvent(new MouseEvent('click',{bubbles:true,...${JSON.stringify(modifiers)}}))`);
  const count = value => wait(`[...document.querySelectorAll('[role=status]')].some(e=>e.textContent==='${value} selected')`, `${value} selected`);
  const key = async (keyCode, modifiers = []) => {
    await ui("document.querySelector('[data-testid=data-grid-scroll]').focus()");
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers });
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers });
    await pause(50);
  };
  await rowClick(3, { ctrlKey: true }); await count(2);
  assert.equal(await ui("document.querySelector('tr[data-focused=true]').dataset.entryId"), '3');
  assert.deepEqual(await ui("[...document.querySelectorAll('tr[aria-selected=true]')].map(r=>Number(r.dataset.entryId))"), [1, 3]);
  const capturePath = require('node:path').resolve('.dist/explorer-selection.png');
  require('node:fs').mkdirSync(require('node:path').dirname(capturePath), { recursive: true });
  require('node:fs').writeFileSync(capturePath, (await window.webContents.capturePage()).toPNG());
  await rowClick(3, { ctrlKey: true }); await count(1);
  await rowClick(2); await count(1);
  await rowClick(5, { shiftKey: true }); await count(4);
  await rowClick(3, { shiftKey: true }); await count(2);
  await key('DOWN', ['shift']); await count(3);
  await key('DOWN', ['control']); await count(3);
  await key('SPACE', ['control']); await count(4);
  await key('ESCAPE'); await count(0);
  assert.equal(await ui("document.querySelector('tr[data-focused=true]').dataset.entryId"), '5');
  await rowClick(1);
  await scrollToEnd();
  await ui('window.appRegression.pending.shift()()');
  await wait("document.body.textContent.includes('1000 of 1000')", 'selection across paging');
  await scrollToEnd();
  await wait("!!document.querySelector('tr[data-entry-id=\"1000\"]')", 'last row rendered');
  await rowClick(1000, { shiftKey: true }); await count(1000);
  await rowClick(999, { shiftKey: true }); await count(999);
  await ui("document.querySelector('th[title=Formula]').click()");
  await wait("document.body.textContent.includes('500 of 1000')", 'sorted first page');
  await count(999);
  await search(); await count(1);
  await key('A', ['control']); await count(1000);
  assert.ok(await ui("document.body.textContent.includes('500 of 1000')"), 'Ctrl+A does not fetch unloaded rows');
  await rowClick(2, { ctrlKey: true }); await count(999);
  await ui(`window.batchHarness = {}; window.cifApi.onBatchExportProgress = listener => { window.batchHarness.progress=listener; return ()=>{}; };
    window.cifApi.countBatchExport = async scope => scope.kind==='selected' ? scope.ids.length : 1000-(scope.excludedIds?.length??0);
    window.cifApi.batchExport = request => { window.batchHarness.request=request; window.batchHarness.progress({total:request.expectedCount,completed:1,failed:0,notAttempted:request.expectedCount-1}); return new Promise(resolve=>window.batchHarness.resolve=resolve); };
    window.cifApi.cancelBatchExport = async () => { const total=window.batchHarness.request.expectedCount; window.batchHarness.resolve({total,completed:1,failed:1,notAttempted:total-2,cancelled:true,folderName:'cif_batch_2026-09-20_14-30-05',failures:[{entryId:3,reason:'Verified stored block unavailable.'}]}); return true; }; undefined`);
  await click('Export\u2026');
  await wait("document.querySelector('dialog')?.textContent.includes('999 structures will be requested')", 'all except selected scope');
  await ui("document.querySelectorAll('input[name=batch-scope]')[2].click()");
  await wait("document.querySelector('dialog')?.textContent.includes('1000 structures will be requested')", 'all matching scope');
  await ui("document.querySelectorAll('input[name=batch-scope]')[1].click()");
  await wait("document.querySelector('dialog')?.textContent.includes('999 structures will be requested')", 'selected scope restored');
  assert.equal(await ui("!!document.querySelector('[aria-label=\"Batch export format\"]')"), false);
  assert.ok(await ui("document.querySelector('dialog').textContent.includes('Only CIF files')"));
  await click('Choose folder and export');
  await wait("document.querySelector('dialog')?.textContent.includes('1 completed, 0 failed of 999')", 'progress');
  assert.equal(await ui('window.batchHarness.request.scope.kind'), 'matching');
  assert.deepEqual(await ui('window.batchHarness.request.scope.excludedIds'), [2]);
  assert.equal(await ui("'mode' in window.batchHarness.request"), false);
  assert.ok(await ui("[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Import CIFs')).disabled"));
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ESCAPE' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ESCAPE' });
  await pause(50);
  assert.ok(await ui("document.querySelector('dialog').open"), 'running export remains visible');
  await count(999);
  await click('Cancel export');
  await wait("document.querySelector('dialog')?.textContent.includes('Export cancelled')", 'cancelled outcome');
  assert.ok(await ui("document.querySelector('dialog').textContent.includes('1 completed; 1 failed; 997 not attempted')"));
  await ui("document.querySelector('dialog details summary').click()");
  assert.ok(await ui("document.querySelector('dialog details').innerText.includes('Entry 3: Verified stored block unavailable.')"));
  assert.ok(await ui("document.querySelector('dialog').textContent.includes('cif_batch_2026-09-20_14-30-05')"));
  await click('Close');
  await search(); await count(1);
  await ui("window.cifApi.importCifFolder=async()=>({importedCount:1,skippedCount:0,failures:[],total:1}); undefined");
  await click('Import CIFs'); await count(0);
  await search();
  console.log('✓ Explorer click/Ctrl/Shift/keyboard selection, cross-page ranges, all-match exclusions, sort/reset, export progress and cancellation');
};
