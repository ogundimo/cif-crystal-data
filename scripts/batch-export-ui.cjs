const assert = require('node:assert/strict');

module.exports = async function batchExportUi(window, { search, scrollToEnd, waitForRenderer, pause }) {
  const ui = expression => window.webContents.executeJavaScript(expression);
  const click = text => ui(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes(${JSON.stringify(text)})).click()`);
  const wait = (expression, label) => waitForRenderer(window, expression, label);
  await search();
  await ui("document.querySelector('input[aria-label=\"Select entry 1 for batch export\"]').click()");
  await wait("document.body.textContent.includes('1 selected for batch export')", 'mouse batch selection');
  assert.equal(await ui("document.querySelector('tr[aria-selected=true]').dataset.entryId"), '1');
  await ui("document.querySelector('[data-testid=data-grid-scroll]').focus()");
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'DOWN' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'DOWN' });
  await pause(50);
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'SPACE' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'SPACE' });
  await wait("document.body.textContent.includes('2 selected for batch export')", 'keyboard batch selection');
  await scrollToEnd();
  await ui('window.appRegression.pending.shift()()');
  await wait("document.body.textContent.includes('1000 of 1000')", 'batch selection across paging');
  assert.ok(await ui("document.body.textContent.includes('2 selected for batch export')"));
  await ui("document.querySelector('th[title=Formula]').click()");
  await pause(100);
  assert.ok(await ui("document.body.textContent.includes('2 selected for batch export')"));
  await ui(`window.batchHarness = {}; window.cifApi.onBatchExportProgress = listener => { window.batchHarness.progress=listener; return ()=>{}; };
    window.cifApi.batchExport = request => { window.batchHarness.request=request; window.batchHarness.progress({total:request.expectedCount,completed:1,failed:0,notAttempted:request.expectedCount-1}); return new Promise(resolve=>window.batchHarness.resolve=resolve); };
    window.cifApi.cancelBatchExport = async () => { const total=window.batchHarness.request.expectedCount; window.batchHarness.resolve({total,completed:1,failed:1,notAttempted:total-2,cancelled:true,folderName:'cif-export-test',reportName:'summary.csv'}); return true; }; undefined`);
  await click('Batch export');
  await wait("document.querySelector('dialog')?.textContent.includes('2 structures will be requested')", 'selected count');
  await ui("document.querySelectorAll('input[name=batch-scope]')[1].click()");
  await wait("document.querySelector('dialog')?.textContent.includes('1205 structures will be requested')", 'all matching count beyond loaded rows');
  await click('Choose folder and export');
  await wait("document.querySelector('dialog')?.textContent.includes('1 completed, 0 failed of 1205')", 'progress');
  assert.equal(await ui('window.batchHarness.request.scope.kind'), 'matching');
  assert.ok(await ui("[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Import CIFs')).disabled"));
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ESCAPE' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ESCAPE' });
  await pause(50);
  assert.ok(await ui("document.querySelector('dialog').open"), 'running export remains visible');
  await click('Cancel export');
  await wait("document.querySelector('dialog')?.textContent.includes('Export cancelled')", 'cancelled outcome');
  assert.ok(await ui("document.querySelector('dialog').textContent.includes('1 completed; 1 failed; 1203 not attempted')"));
  await click('Close');
  await search();
  assert.ok(await ui("document.body.textContent.includes('0 selected for batch export')"));
  await ui("document.querySelector('input[aria-label=\"Select entry 1 for batch export\"]').click(); window.cifApi.importCifFolder=async()=>({importedCount:1,skippedCount:0,failures:[],total:1}); undefined");
  await click('Import CIFs');
  await wait("document.body.textContent.includes('0 selected for batch export')", 'data change clears selection');
  await search();
  console.log('✓ batch mouse/keyboard selection, paging/sort retention, filter/import reset, exact scopes, progress and cancellation');
};
